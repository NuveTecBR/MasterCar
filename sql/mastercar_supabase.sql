CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  cargo TEXT NOT NULL DEFAULT 'chefe_oficina',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS servicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,
  nome TEXT NOT NULL,
  categoria TEXT NOT NULL,
  preco_base NUMERIC(10,2) NOT NULL CHECK (preco_base > 0),
  tempo_estimado TEXT NOT NULL,
  garantia_meses INTEGER NOT NULL DEFAULT 6,
  descricao TEXT NOT NULL,
  inclui_itens TEXT NOT NULL,
  destaque BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS ordens_servico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo_os TEXT NOT NULL UNIQUE,
  placa_veiculo TEXT NOT NULL,
  modelo_veiculo TEXT NOT NULL,
  nome_cliente TEXT NOT NULL,
  servico_principal TEXT NOT NULL,
  etapa_atual TEXT NOT NULL,
  progresso_pct INTEGER NOT NULL DEFAULT 20,
  mecanico_responsavel TEXT NOT NULL,
  relatorio_tecnico TEXT NOT NULL,
  valor_orcamento NUMERIC(10,2) NOT NULL,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS agendamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  servico_id BIGINT NOT NULL REFERENCES servicos(id) ON DELETE CASCADE,
  tipo_solicitacao TEXT NOT NULL DEFAULT 'Agendamento Oficina',
  nome_cliente TEXT NOT NULL,
  telefone TEXT NOT NULL,
  placa_veiculo TEXT NOT NULL,
  modelo_veiculo TEXT NOT NULL,
  porte_veiculo TEXT NOT NULL DEFAULT 'Leve (Hatch/Sedan)',
  valor_estimado NUMERIC(10,2) NOT NULL,
  sintomas_relatados TEXT,
  consentimento_lgpd BOOLEAN NOT NULL DEFAULT TRUE,
  status TEXT NOT NULL DEFAULT 'Aguardando Confirmação',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS solicitacoes_lgpd (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo TEXT NOT NULL UNIQUE,
  nome_titular TEXT NOT NULL,
  email_titular TEXT NOT NULL,
  tipo_direito TEXT NOT NULL,
  detalhes TEXT,
  status TEXT NOT NULL DEFAULT 'Recebido',
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE ordens_servico ENABLE ROW LEVEL SECURITY;
ALTER TABLE agendamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitacoes_lgpd ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Leitura publica de servicos" ON servicos FOR SELECT USING (true);
CREATE POLICY "Apenas backend acessa ordens" ON ordens_servico FOR ALL USING (false);
CREATE POLICY "Apenas backend acessa agendamentos" ON agendamentos FOR ALL USING (false);
